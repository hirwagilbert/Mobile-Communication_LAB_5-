"""
Mini Project 5.1 - Part A
Simulating cellular-style challenge-response (mutual) authentication.

Conceptual model: GSM A3/A8 and the 3G/4G/5G AKA family.
  K        -> long-term shared secret (Ki on the SIM/USIM and in the AuC)
  RAND     -> fresh random challenge generated by the home network
  RES/XRES -> response computed by the device / expected response at the network
  Kc/CK    -> session key derived from K and RAND (never transmitted)

Python 3 standard library only (hashlib, hmac, secrets).
Run:  python part_a_mutual_auth.py
"""

import hashlib
import hmac
import secrets

RAND_LEN = 16        # bytes (128-bit challenge, same size as GSM/UMTS RAND)
KEY_LEN = 32         # bytes (256-bit shared secret K)


# ---------------------------------------------------------------------------
# Core primitives (Procedure steps 2-4)
# ---------------------------------------------------------------------------
def generate_rand() -> bytes:
    """Fresh, unpredictable challenge (RAND). Called only by HomeNetwork."""
    return secrets.token_bytes(RAND_LEN)


def compute_response(K: bytes, RAND: bytes) -> bytes:
    """A3-style response: RES = HMAC-SHA256(K, RAND)."""
    return hmac.new(K, RAND, hashlib.sha256).digest()


def derive_session_key(K: bytes, RAND: bytes) -> bytes:
    """A8-style key derivation with a distinct label so that the session key
    and the response are cryptographically independent outputs of one K
    (mirrors AKA deriving separate RES, CK and IK values)."""
    return hmac.new(K, b"SESSIONKEY" + RAND, hashlib.sha256).digest()


def compute_network_token(K: bytes, RAND: bytes, SQN: int) -> bytes:
    """Lab Task 3: network authentication token (simplified AUTN/MAC).
    A different label again keeps it independent from RES and the session key."""
    return hmac.new(K, b"NETAUTH" + RAND + SQN.to_bytes(6, "big"),
                    hashlib.sha256).digest()


# WHY AN EAVESDROPPER CANNOT WIN (Procedure step 9)
# HMAC-SHA256 is a one-way, keyed pseudorandom function (PRF). Without K its
# outputs look like independent random strings, so:
#   * an observed (RAND, RES) pair does not reveal K - recovering K would mean
#     inverting SHA-256 inside HMAC or brute-forcing a 2^256 key space;
#   * the pair does not help predict HMAC(K, RAND2) for any unseen RAND2 -
#     each new challenge gives an output unrelated to the previous ones.
# Freshness of RAND is what turns these two properties into replay resistance.


def short(b: bytes, n: int = 16) -> str:
    """Print-friendly hex prefix of a byte string."""
    return b.hex()[:n] + "..."


# ---------------------------------------------------------------------------
# Entities (Procedure step 1)
# ---------------------------------------------------------------------------
class Channel:
    """Radio interface: records everything that is 'sent' so we can prove
    that K and the session key never cross it."""

    def __init__(self):
        self.messages = []

    def send(self, sender, receiver, label, payload: bytes):
        self.messages.append((sender, receiver, label, payload))
        print(f"   [air] {sender:>11} -> {receiver:<11} {label:<5} = {short(payload, 32)}")
        return payload

    def contains(self, secret: bytes) -> bool:
        return any(secret in m[3] for m in self.messages)


class Device:
    """Mobile station / UE holding K on its SIM (never transmitted)."""

    def __init__(self, K: bytes, name: str = "Device"):
        self._K = K
        self.name = name
        self.session_key = None
        self.last_sqn = 0                 # Lab Task 3: highest SQN accepted

    def answer_challenge(self, RAND: bytes) -> bytes:
        self.session_key = derive_session_key(self._K, RAND)
        return compute_response(self._K, RAND)

    # Lab Task 3 - device authenticates the network before answering
    def verify_network(self, RAND: bytes, SQN: int, token: bytes) -> bool:
        expected = compute_network_token(self._K, RAND, SQN)
        if not hmac.compare_digest(expected, token):
            print("   Device: network token INVALID -> fake base station rejected")
            return False
        if SQN <= self.last_sqn:
            print(f"   Device: SQN {SQN} <= last accepted {self.last_sqn} "
                  "-> replayed challenge rejected")
            return False
        self.last_sqn = SQN
        print(f"   Device: network token valid and SQN {SQN} is fresh -> network authenticated")
        return True


class HomeNetwork:
    """Home network / AuC holding the same K."""

    def __init__(self, K: bytes, track_used_rands: bool = False):
        self._K = K
        self.track_used_rands = track_used_rands
        self.used_rands = set()
        self.pending = None               # RAND of the current attempt
        self.session_key = None
        self.sqn = 0

    def new_challenge(self) -> bytes:
        RAND = generate_rand()
        self.pending = RAND
        return RAND

    def network_token(self, RAND: bytes):
        self.sqn += 1
        return self.sqn, compute_network_token(self._K, RAND, self.sqn)

    def verify(self, RAND_claimed: bytes, RES: bytes) -> bool:
        """Verify a response. A naive network trusts the RAND carried in the
        message; a hardened network checks that it is the challenge it just
        issued and that the RAND has never been used before."""
        if self.track_used_rands:
            if RAND_claimed in self.used_rands:
                print("   HomeNetwork: RAND already used -> REPLAY REJECTED")
                return False
            if RAND_claimed != self.pending:
                print("   HomeNetwork: RAND is not the outstanding challenge -> REJECTED")
                return False
        XRES = compute_response(self._K, RAND_claimed)
        ok = hmac.compare_digest(XRES, RES)
        if ok:
            self.used_rands.add(RAND_claimed)
            self.session_key = derive_session_key(self._K, RAND_claimed)
        self.pending = None
        return ok


class Attacker:
    """Passive eavesdropper: sees only what crossed the channel. No reference to K."""

    def __init__(self, observed_rand: bytes, observed_res: bytes):
        self.observed_rand = observed_rand
        self.observed_res = observed_res

    def replay_old_response(self, _new_rand: bytes) -> bytes:
        return self.observed_res

    def guess_key_by_inspection(self):
        """Naive 'inspection' guesses built only from the observed pair."""
        r, s = self.observed_rand, self.observed_res
        return {
            "K = observed RES": s,
            "K = observed RAND": r,
            "K = RAND xor RES[:16] (x2)": bytes(a ^ b for a, b in zip(r, s[:16])) * 2,
            "K = SHA256(RAND)": hashlib.sha256(r).digest(),
            "K = SHA256(RAND||RES)": hashlib.sha256(r + s).digest(),
        }

    def brute_force(self, attempts: int):
        """Random key guesses checked against the observed pair."""
        for _ in range(attempts):
            guess = secrets.token_bytes(KEY_LEN)
            if hmac.compare_digest(compute_response(guess, self.observed_rand),
                                   self.observed_res):
                return guess
        return None



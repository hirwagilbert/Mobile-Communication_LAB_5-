# Scenarios
# ---------------------------------------------------------------------------
def run_authentication(K: bytes, run_no: int = 1):
    """Procedure steps 5-6: one successful authentication run."""
    print(f"\n--- Authentication run #{run_no} ---")
    ch = Channel()
    dev, net = Device(K), HomeNetwork(K)

    RAND = ch.send("HomeNetwork", "Device", "RAND", net.new_challenge())
    RES = ch.send("Device", "HomeNetwork", "RES", dev.answer_challenge(RAND))
    ok = net.verify(RAND, RES)

    XRES = compute_response(K, RAND)
    print(f"   RES  (device)  = {short(RES, 32)}")
    print(f"   XRES (network) = {short(XRES, 32)}")
    print(f"   Result         : {'AUTHENTICATION SUCCESS' if ok else 'FAILURE'}")
    print(f"   Kc at device   = {short(dev.session_key, 32)}")
    print(f"   Kc at network  = {short(net.session_key, 32)}")
    same = hmac.compare_digest(dev.session_key, net.session_key)
    print(f"   Session keys identical          : {same}")
    print(f"   K ever sent over the channel    : {ch.contains(K)}")
    print(f"   Kc ever sent over the channel   : {ch.contains(dev.session_key)}")
    print(f"   RES differs from session key    : {RES != dev.session_key}")
    return RAND, RES, dev.session_key


def run_forgery(K: bytes, RAND: bytes, RES: bytes):
    """Procedure steps 7-8: attacker tries to answer a new challenge."""
    print("\n--- Forgery attempt by a passive attacker ---")
    atk = Attacker(RAND, RES)
    RAND2 = generate_rand()
    correct = compute_response(K, RAND2)           # what the network expects
    print(f"   New challenge RAND2 = {short(RAND2, 32)}")

    replay = atk.replay_old_response(RAND2)
    print(f"   [1] Replay old RES             -> match = "
          f"{hmac.compare_digest(replay, correct)}")

    for name, guess in atk.guess_key_by_inspection().items():
        forged = compute_response(guess, RAND2)
        print(f"   [2] Guess {name:<28}-> match = {hmac.compare_digest(forged, correct)}")

    n = 20000
    found = atk.brute_force(n)
    print(f"   [3] Brute force {n} random keys -> key found = {found is not None} "
          f"(key space = 2^{KEY_LEN * 8})")
    print("   Conclusion: one observed (RAND, RES) pair gives no way to forge RES2.")


def lab_task_1_replay(K: bytes):
    """Lab Task 1: replay attack against a naive and a hardened network."""
    print("\n--- Lab Task 1: replay attack ---")
    dev = Device(K)

    # Capture a legitimate exchange
    naive = HomeNetwork(K, track_used_rands=False)
    RAND = naive.new_challenge()
    RES = dev.answer_challenge(RAND)
    print(f"   Legitimate run accepted          : {naive.verify(RAND, RES)}")

    # (a) Old RES against a NEW RAND -> fails on any network
    RAND_new = naive.new_challenge()
    print(f"   (a) Old RES vs new RAND accepted : {naive.verify(RAND_new, RES)}")

    # (b) Replay the whole old (RAND, RES) message to a NAIVE network that
    #     trusts the RAND carried in the message -> accepted (vulnerability)
    naive.new_challenge()
    print(f"   (b) Full replay, naive network   : {naive.verify(RAND, RES)}  <-- vulnerable")

    # (c) Same replay against a network that tracks used RAND values
    hard = HomeNetwork(K, track_used_rands=True)
    R1 = hard.new_challenge()
    captured_res = dev.answer_challenge(R1)            # attacker records this
    print(f"   (c) Legit run, hardened network  : {hard.verify(R1, captured_res)}")
    hard.new_challenge()
    print(f"       Full replay, hardened network: {hard.verify(R1, captured_res)}")


def lab_task_3_mutual(K: bytes):
    """Lab Task 3: network also proves itself to the device (UMTS-style AUTN)."""
    print("\n--- Lab Task 3: mutual authentication ---")
    dev = Device(K)
    net = HomeNetwork(K, track_used_rands=True)

    RAND = net.new_challenge()
    SQN, token = net.network_token(RAND)
    print("   Genuine network sends RAND + AUTN-like token")
    if dev.verify_network(RAND, SQN, token):
        print(f"   Device response accepted          : {net.verify(RAND, dev.answer_challenge(RAND))}")

    print("   Fake base station (no K) sends RAND + random token")
    fake_rand = generate_rand()
    dev.verify_network(fake_rand, SQN + 1, secrets.token_bytes(32))

    print("   Attacker replays the earlier genuine RAND + token")
    dev.verify_network(RAND, SQN, token)


def main():
    print("=" * 72)
    print("MINI PROJECT 5.1 - PART A: CHALLENGE-RESPONSE AUTHENTICATION")
    print("=" * 72)
    K = secrets.token_bytes(KEY_LEN)
    print(f"Shared secret K provisioned in Device (SIM) and HomeNetwork (AuC).")
    print(f"K is {KEY_LEN * 8} bits and is NEVER printed or transmitted.")

    RAND, RES, _ = run_authentication(K, 1)
    run_forgery(K, RAND, RES)
    lab_task_1_replay(K)
    lab_task_3_mutual(K)

    print("\n--- Re-running: fresh RAND and session key every time ---")
    for i in range(2, 5):
        dev, net = Device(K), HomeNetwork(K)
        R = net.new_challenge()
        ok = net.verify(R, dev.answer_challenge(R))
        print(f"   run #{i}: RAND={short(R)} Kc={short(dev.session_key)} success={ok}")
    print("\nDone.")


if __name__ == "__main__":
    main()
